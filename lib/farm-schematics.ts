/** 자동 농장 3D 복셀 — 실제 튜토리얼 영상 기준 (X/Z 가로, Y 위) */
export type FarmVoxel = {
  x: number;
  y: number;
  z: number;
  block: string;
};

export type FarmSchematic = {
  id: string;
  caption: string;
  blocks: FarmVoxel[];
  cameraDistance?: number;
};

function v(x: number, y: number, z: number, block: string): FarmVoxel {
  return { x, y, z, block };
}

function row(
  y: number,
  z: number,
  cells: (string | null)[],
  x0 = 0
): FarmVoxel[] {
  return cells.flatMap((block, i) =>
    block ? [v(x0 + i, y, z, block)] : []
  );
}

/** 사탕수수·대나무 공통 — 유리 수직 모듈 + 옵저버/피스톤 */
